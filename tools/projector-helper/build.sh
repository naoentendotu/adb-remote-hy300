#!/usr/bin/env sh
# Rebuilds src/services/adb/helperDex.ts from the Java sources here. Needs a JDK and the Android SDK (build-tools + a platform).
set -e
SDK="${ANDROID_HOME:-$LOCALAPPDATA/Android/Sdk}"
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
JAR="$SDK/platforms/$(ls "$SDK/platforms" | sort -V | tail -1)/android.jar"
DIR="$(cd "$(dirname "$0")" && pwd)"
OUT="$(mktemp -d)"
javac -source 8 -target 8 -nowarn -cp "$JAR" -d "$OUT" "$DIR"/dev/hy300/helper/*.java
D8="$BT/d8"; [ -f "$D8" ] || D8="$BT/d8.bat"
"$D8" --min-api 26 --output "$OUT" "$OUT"/dev/hy300/helper/*.class
{
  echo '// Generated by tools/projector-helper/build.sh. Do not edit.'
  printf "export const HELPER_DEX = '%s';\n" "$(base64 -w0 "$OUT/classes.dex")"
} > "$DIR/../../src/services/adb/helperDex.ts"
rm -rf "$OUT"
